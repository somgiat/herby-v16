# แนวคิดใหม่: What Herby Learned สร้างจากสิ่งที่สังเกตเห็น

import streamlit as st

st.set_page_config(page_title="Herby V0.7", page_icon="❤️", layout="centered")

HIGH_RISK = ["Bitcoin","Cryptocurrency","หุ้นไทย","หุ้นต่างประเทศ","ETF"]
LOW_RISK = ["เงินฝาก","พันธบัตร","ตราสารหนี้"]

if "started" not in st.session_state:
    st.session_state.started = False

if not st.session_state.started:
    st.title("❤️ Herby")
    st.subheader("Your Digital Financial Mentor")
    st.markdown("""
### เราไม่ได้ช่วยคุณเลือกสินทรัพย์
### เราช่วยให้คุณเข้าใจตัวเองมากขึ้น
""")

    if st.button("🚀 เริ่มต้นกับ Herby"):
        st.session_state.started = True
        st.rerun()

else:
    st.title("👋 ยินดีต้อนรับ")

    name = st.text_input("คุณอยากให้ Herby เรียกคุณว่าอะไร?")

    if name:

        st.success(f"สวัสดี {name} 👋 ยินดีต้อนรับสู่ Herby")

        age = st.selectbox(
            "คุณอยู่ในช่วงอายุใด?",
            ["18-24 ปี","25-34 ปี","35-44 ปี","45-54 ปี","55 ปีขึ้นไป"]
        )

        goal = st.selectbox(
            "เป้าหมายหลักในการลงทุนของคุณคืออะไร?",
            ["เกษียณ","อิสรภาพทางการเงิน","สร้างความมั่งคั่งระยะยาว","ซื้อบ้าน","การศึกษาบุตร","อื่น ๆ"]
        )

        timeline = st.selectbox(
            "คุณคาดว่าจะใช้เงินก้อนนี้เมื่อไร?",
            ["น้อยกว่า 3 ปี","3-5 ปี","5-10 ปี","10-20 ปี","มากกว่า 20 ปี"]
        )

        experience = st.selectbox(
            "คุณมีประสบการณ์การลงทุนมากแค่ไหน?",
            ["ยังไม่เคยลงทุน","น้อยกว่า 1 ปี","1-3 ปี","3-10 ปี","มากกว่า 10 ปี"]
        )

        assets = st.multiselect(
            "คุณสนใจสินทรัพย์ประเภทใดเป็นพิเศษ?",
            ["เงินฝาก","พันธบัตร","ตราสารหนี้","กองทุนรวม","RMF / SSF","REIT","ทองคำ","ETF","หุ้นไทย","หุ้นต่างประเทศ","Bitcoin","Cryptocurrency"]
        )

        feeling = st.radio(
            "คุณรู้สึกอย่างไร หากมูลค่าการลงทุนของคุณลดลง 30%?",
            [
                "กังวลมากและอยากขายออกทันที",
                "กังวล แต่คงขายบางส่วน",
                "ไม่สบายใจ แต่ยังถือไว้ได้",
                "มองว่าเป็นเรื่องปกติของการลงทุน",
                "มองว่าอาจเป็นโอกาสในการซื้อเพิ่ม"
            ]
        )

        volatility = st.slider(
            "คุณยอมรับความผันผวนได้มากแค่ไหน?",
            1,10,5
        )

        if st.button("🔍 วิเคราะห์สไตล์การลงทุน"):

            issues=[]

            if goal == "เกษียณ" and timeline in ["น้อยกว่า 3 ปี","3-5 ปี"]:
                issues.append("คุณมีเป้าหมายเกษียณ แต่ระบุว่าจะใช้เงินในระยะค่อนข้างสั้น")

            if experience == "ยังไม่เคยลงทุน" and any(a in assets for a in HIGH_RISK):
                issues.append("คุณยังไม่เคยลงทุน แต่สนใจสินทรัพย์ที่มีความผันผวนสูง")

            if feeling == "กังวลมากและอยากขายออกทันที" and any(a in assets for a in HIGH_RISK):
                issues.append("คุณสนใจสินทรัพย์ความเสี่ยงสูง แต่บอกว่ามีแนวโน้มขายทันทีเมื่อขาดทุนหนัก")

            if volatility >= 7 and len(assets)>0 and all(a in LOW_RISK for a in assets):
                issues.append("คุณบอกว่ารับความเสี่ยงได้สูง แต่เลือกสินทรัพย์ความเสี่ยงต่ำ")

            if goal == "อิสรภาพทางการเงิน" and len(assets)>0 and all(a in LOW_RISK for a in assets):
                issues.append("เป้าหมายของคุณต้องการการเติบโต แต่สินทรัพย์ที่เลือกเน้นความมั่นคง")

            st.header("🚨 สิ่งที่ Herby สังเกตเห็น")

            if issues:
                for item in issues:
                    st.warning(item)
            else:
                st.success("Herby ยังไม่พบความขัดแย้งสำคัญจากคำตอบของคุณ")

            st.header("🌟 What Herby Learned About You")

            if len(issues) >= 2:
                st.info("Herby มองว่าคุณกำลังอยู่ในช่วงค้นหาสไตล์การลงทุนที่เหมาะกับตัวเอง คำตอบบางส่วนสะท้อนความต้องการผลตอบแทนที่สูงขึ้น แต่บางส่วนสะท้อนความกังวลต่อความเสี่ยง ซึ่งเป็นเรื่องปกติของนักลงทุนที่กำลังเรียนรู้")
            elif experience == "ยังไม่เคยลงทุน" and any(a in assets for a in ["Bitcoin","Cryptocurrency"]):
                st.info("Herby สังเกตว่าคุณสนใจสินทรัพย์ที่มีโอกาสเติบโตสูงมาก แม้ยังมีประสบการณ์ลงทุนไม่มาก สิ่งสำคัญในช่วงนี้อาจไม่ใช่การเลือกสินทรัพย์ที่ดีที่สุด แต่เป็นการเข้าใจความเสี่ยงที่มาพร้อมกับผลตอบแทน")
            else:
                st.info("Herby มองว่าคำตอบของคุณสะท้อนรูปแบบการลงทุนที่ค่อนข้างชัดเจน และมีความสอดคล้องกันในหลายมิติ")

            st.header("📈 สไตล์การลงทุนปัจจุบันของคุณ")

            if feeling == "กังวลมากและอยากขายออกทันที":
                style = "🛡️ นักลงทุนสายระมัดระวัง"
                desc = "ให้ความสำคัญกับการรักษาเงินต้น และหลีกเลี่ยงการขาดทุนรุนแรง"
            elif feeling == "กังวล แต่คงขายบางส่วน":
                style = "⚖️ นักลงทุนสายสมดุล"
                desc = "ต้องการเติบโต แต่ยังต้องการควบคุมความเสี่ยง"
            elif feeling == "ไม่สบายใจ แต่ยังถือไว้ได้":
                style = "📈 นักลงทุนสายเติบโต"
                desc = "ยอมรับความผันผวนได้ระดับหนึ่งเพื่อผลตอบแทนระยะยาว"
            elif feeling == "มองว่าเป็นเรื่องปกติของการลงทุน":
                style = "📈 นักลงทุนสายเติบโตระยะยาว"
                desc = "เข้าใจธรรมชาติของตลาดและพร้อมผ่านช่วงผันผวน"
            else:
                style = "🚀 นักลงทุนสายรุก"
                desc = "มองความผันผวนเป็นโอกาสและเน้นการเติบโตสูง"

            st.subheader(style)
            st.write(desc)

            st.header("❓ Herby เข้าใจคุณถูกไหม")

            c1,c2 = st.columns(2)

            with c1:
                if st.button("🔄 ฉันว่ายังไม่ใช่ กลับไปแก้ไขคำตอบ"):
                    st.warning("ลองปรับคำตอบที่คิดว่ายังไม่สะท้อนตัวตนของคุณ")

            with c2:
                if st.button("✅ ฉันคิดว่าใช่ ไปขั้นตอนต่อไปกันเลย"):
                    st.success("ยอดเยี่ยม! Herby เริ่มเข้าใจรูปแบบการลงทุนของคุณแล้ว")
